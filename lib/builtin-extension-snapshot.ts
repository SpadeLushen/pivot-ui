import { readBuiltinSettings } from "./builtin-extension-settings";
import { getToolManagementSession } from "./rpc-manager";
import type { BuiltinExtensionsSnapshot } from "./builtin-extension-types";

/** No AgentSession creation, extension evaluation, MCP connections or OAuth. */
export async function readBuiltinSnapshot(cwd: string, sessionId?: string): Promise<BuiltinExtensionsSnapshot> {
  const settings = await readBuiltinSettings(cwd);
  const session = getToolManagementSession(cwd, sessionId);
  const application = session?.getExtensionApplicationState() ?? null;
  // During reload the SDK's current result may only be partially bound.
  const loader = application?.state === "applying" ? undefined : session?.inner.resourceLoader;
  const result = loader?.getExtensions();
  const diagnostics: BuiltinExtensionsSnapshot["diagnostics"] = [];
  for (const error of result?.errors ?? []) {
    // SDK conflict messages have a known prefix; arbitrary extension error bodies
    // may contain secrets. Surface the source but not an unbounded raw error.
    const conflict = /conflict|collision/i.test(error.error);
    diagnostics.push({ type: conflict ? "collision" : "error", path: error.path,
      message: conflict ? "plugins.builtinCollision" : "plugins.builtinLoadError" });
  }
  for (const warning of result?.warnings ?? []) {
    diagnostics.push({ type: "warning", path: warning.path, message: "plugins.builtinWarning" });
  }
  for (const item of [...(loader?.getSkills().diagnostics ?? []),
    ...(loader?.getPrompts?.().diagnostics ?? []), ...(loader?.getThemes?.().diagnostics ?? [])]) {
    const collision = item.collision;
    diagnostics.push({ type: item.type, path: item.path,
      message: collision ? "plugins.builtinCollision" : item.type === "error"
        ? "plugins.builtinLoadError" : "plugins.builtinWarning" });
    if (collision) {
      diagnostics.push({ type: "collision", path: collision.winnerPath, message: "plugins.builtinCollisionWinner" },
        { type: "collision", path: collision.loserPath, message: "plugins.builtinCollisionLoser" });
    }
  }
  return { ...settings, application, diagnostics: diagnostics.slice(0, 100),
    builtins: settings.builtins.map(item => {
      const path = `builtin:${item.name}`;
      const loaded = result ? result.extensions.some(extension => extension.path === path) : null;
      const warnings = (result?.warnings ?? []).filter(warning => warning.path === path);
      const error = result?.errors.some(error => error.path === path);
      const state = !result ? "unknown" : error ? "error" : warnings.length ? "replaced"
        : loaded ? "loaded" : !item.configured && application?.state === "applied" ? "disabled" : "unknown";
      return { ...item, loaded, state,
        // Replacement warnings are generated by the SDK, not Provider responses.
        warnings: warnings.slice(0, 10).map(warning => warning.warning.slice(0, 1200)) };
    }) };
}
